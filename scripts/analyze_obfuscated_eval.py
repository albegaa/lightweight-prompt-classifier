#!/usr/bin/env python3

import argparse
from pathlib import Path

import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)


REQUIRED_COLUMNS = {
    "label",
    "prediction",
    "technique",
    "intensity",
    "changed",
}


def normalize_changed(series):
    if pd.api.types.is_bool_dtype(series):
        return series.astype(bool)

    mapping = {
        "true": True,
        "false": False,
        "1": True,
        "0": False,
        "1.0": True,
        "0.0": False,
    }

    normalized = (
        series.astype(str)
        .str.strip()
        .str.lower()
        .map(mapping)
    )

    if normalized.isna().any():
        bad = sorted(
            series.loc[normalized.isna()]
            .astype(str)
            .unique()
            .tolist()
        )

        raise ValueError(
            "Invalid changed values: "
            f"{bad}"
        )

    return normalized.astype(bool)


def compute_metrics(df):
    y_true = df["label"].astype(int)
    y_pred = df["prediction"].astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        y_pred,
        labels=[0, 1],
    ).ravel()

    accuracy = accuracy_score(
        y_true,
        y_pred,
    )

    precision = precision_score(
        y_true,
        y_pred,
        pos_label=1,
        zero_division=0,
    )

    recall = recall_score(
        y_true,
        y_pred,
        pos_label=1,
        zero_division=0,
    )

    f1 = f1_score(
        y_true,
        y_pred,
        pos_label=1,
        zero_division=0,
    )

    fpr = (
        fp / (fp + tn)
        if (fp + tn) > 0
        else 0.0
    )

    fnr = (
        fn / (fn + tp)
        if (fn + tp) > 0
        else 0.0
    )

    return {
        "n": int(len(df)),
        "accuracy": float(accuracy),
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "fpr": float(fpr),
        "fnr": float(fnr),
        "tp": int(tp),
        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
    }


def summarize_scope(name, df):
    row = {
        "scope": name,
    }

    row.update(
        compute_metrics(df)
    )

    return row


def summarize_group(group):
    total_n = len(group)

    changed = group.loc[
        group["_changed"]
    ].copy()

    changed_n = len(changed)

    row = {
        "total_n": int(total_n),
        "changed_n": int(changed_n),
        "application_rate": (
            changed_n / total_n
            if total_n > 0
            else 0.0
        ),
    }

    if changed_n == 0:
        row.update({
            "accuracy": None,
            "precision": None,
            "recall": None,
            "f1": None,
            "fpr": None,
            "fnr": None,
            "tp": None,
            "tn": None,
            "fp": None,
            "fn": None,
        })

        return pd.Series(row)

    row.update(
        compute_metrics(changed)
    )

    row.pop("n", None)

    return pd.Series(row)


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Analyze Step 1 obfuscated "
            "evaluation predictions."
        )
    )

    parser.add_argument(
        "--predictions",
        required=True,
        help=(
            "predictions.csv generated by "
            "src/classifier/evaluate.py"
        ),
    )

    parser.add_argument(
        "--output-dir",
        required=True,
    )

    args = parser.parse_args()

    input_path = Path(
        args.predictions
    )

    if not input_path.exists():
        raise FileNotFoundError(
            input_path
        )

    df = pd.read_csv(
        input_path
    )

    missing = (
        REQUIRED_COLUMNS
        - set(df.columns)
    )

    if missing:
        raise ValueError(
            "Missing required columns: "
            f"{sorted(missing)}"
        )

    df = df.copy()

    df["label"] = (
        df["label"]
        .astype(int)
    )

    df["prediction"] = (
        df["prediction"]
        .astype(int)
    )

    df["_changed"] = normalize_changed(
        df["changed"]
    )

    output_dir = Path(
        args.output_dir
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ------------------------------------------
    # Overall
    # ------------------------------------------

    overall_rows = [
        summarize_scope(
            "all_rows",
            df,
        )
    ]

    changed_df = df.loc[
        df["_changed"]
    ].copy()

    if len(changed_df) > 0:
        overall_rows.append(
            summarize_scope(
                "changed_only",
                changed_df,
            )
        )

    overall = pd.DataFrame(
        overall_rows
    )

    overall["total_rows"] = len(df)
    overall["changed_rows"] = len(
        changed_df
    )

    overall["application_rate"] = (
        len(changed_df) / len(df)
        if len(df) > 0
        else 0.0
    )

    # ------------------------------------------
    # Technique
    # ------------------------------------------

    by_technique = (
        df.groupby(
            "technique",
            dropna=False,
        )
        .apply(
            summarize_group,
            include_groups=False,
        )
        .reset_index()
    )

    # ------------------------------------------
    # Technique x Intensity
    # ------------------------------------------

    by_cell = (
        df.groupby(
            [
                "technique",
                "intensity",
            ],
            dropna=False,
        )
        .apply(
            summarize_group,
            include_groups=False,
        )
        .reset_index()
    )

    # ------------------------------------------
    # Save
    # ------------------------------------------

    overall_path = (
        output_dir
        / "obfuscated_overall.csv"
    )

    technique_path = (
        output_dir
        / "obfuscated_by_technique.csv"
    )

    cell_path = (
        output_dir
        / "obfuscated_by_cell.csv"
    )

    overall.to_csv(
        overall_path,
        index=False,
        encoding="utf-8-sig",
        float_format="%.6f",
    )

    by_technique.to_csv(
        technique_path,
        index=False,
        encoding="utf-8-sig",
        float_format="%.6f",
    )

    by_cell.to_csv(
        cell_path,
        index=False,
        encoding="utf-8-sig",
        float_format="%.6f",
    )

    print(
        "===== OBFUSCATED EVALUATION ANALYSIS ====="
    )

    print()
    print(
        overall
        .round(4)
        .to_string(index=False)
    )

    print()
    print("Saved:")
    print(overall_path)
    print(technique_path)
    print(cell_path)


if __name__ == "__main__":
    main()
